export function passportLabel(identifier: string): string | null {
  const key = `0x${identifier.replace(/^0x/i, "").toUpperCase()}`;
  const plain = PASSPORT_LABELS[key];
  if (plain !== undefined) return t(plain);
  const numbered = PASSPORT_NUMBERED.find(([id]) => id === key);
  if (numbered !== undefined) return t(numbered[2], { n: numbered[1] });
  return null;
}

/**
 * Why a live read dropped an entry, in the interface's language. The module's
 * own refusal keeps its protocol name — `RequestOutOfRange` is what the
 * standard calls it — and the sentence around it is translated.
 */
export function liveReadReason(reason: string): string {
  const declined = /^the module declined: (.+)$/.exec(reason);
  if (declined !== null) {
    return t("the module declined: {code}", { code: declined[1] });
  }
  return t(reason);
}

/**
 * A help screen's lines for the interface language: ours when the shell sent
 * them, otherwise the English it sent (`ADR-0026`). The lists must be the
 * same length — a screen read half in one language and half in another would
 * be worse than one read wholly in English — so a mismatch falls back rather
 * than interleaving.
 */
export function helpLines(
  texts: Record<string, string[]> | undefined,
  english: string[],
  language: Language,
): string[] {
  const code = productLanguage(language);
  const ours = code !== null ? texts?.[code] : undefined;
  if (ours === undefined || ours.length !== english.length) return english;
  return ours;
}

